export type IconName = keyof typeof PATHS;

/** Pleines plutôt qu'au trait : petites, elles se lisent mieux ainsi. */
const FILLED: ReadonlySet<string> = new Set(["play", "pause", "vote-up", "vote-down", "dot"]);

const escAttr = (s: string): string => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

/**
 * L'icône en SVG. Sans `label`, elle est décorative (le texte à côté dit ce qu'elle veut dire) ;
 * avec, le libellé est lu par les lecteurs d'écran (icône seule, hors d'un bouton qui a son aria-label).
 */
export function icon(name: IconName, label?: string): string {
  const svg = `<svg class="ic ic-${name}${FILLED.has(name) ? " fill" : ""}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${PATHS[name]}</svg>`;
  return label ? `${svg}<span class="sr-only">${escAttr(label)}</span>` : svg;
}

/** L'icône dans un dessin SVG (schéma, grille), coin haut gauche en (x, y), de côté `size`. */
export function iconAt(name: IconName, x: number, y: number, size: number, cls = ""): string {
  return `<svg class="ic ic-${name}${FILLED.has(name) ? " fill" : ""}${cls ? ` ${cls}` : ""}" x="${x}" y="${y}" width="${size}" height="${size}" style="width:${size}px;height:${size}px" viewBox="0 0 24 24" aria-hidden="true">${PATHS[name]}</svg>`;
}

export const isIcon =(name: string): name is IconName => Object.hasOwn(PATHS, name);

const TOKEN = /\{i:([a-z-]+)\}/g;

/** Dessine les « {i:nom} » d'un texte déjà prêt pour du HTML (échappé, ou balisé par le catalogue). */
export function withIcons(html: string): string {
  return html.replace(TOKEN, (all, n: string) => (isIcon(n) ? icon(n) : all));
}

/** Retire les « {i:nom} » (attribut, texte brut), avec l'espace qui les sépare du mot. */
export function noIcons(text: string): string {
  return text.replace(/\{i:[a-z-]+\} /g, "").replace(/ ?\{i:[a-z-]+\}/g, "");
}
